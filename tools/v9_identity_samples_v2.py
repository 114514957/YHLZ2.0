def check() -> int:
    errs = []
    by_tag: dict[str, int] = {}
    by_target: dict[str, int] = {}
    for i, (q, a, tag, target) in enumerate(RECORDS, 1):
        by_tag[tag] = by_tag.get(tag, 0) + 1
        by_target[target] = by_target.get(target, 0) + 1
        # 1. 长度
        if len(a) > 80:
            errs.append("#%d [%s] 回答 %d 字 > 80：%s" % (i, tag, len(a), a[:40]))
        # 2. 反问结尾
        if a.rstrip("”\"'」』）) ")[-1:] in ("？", "?"):
            errs.append("#%d [%s] 以问号结尾：%s" % (i, tag, a[:40]))
        # 3. 客服腔词
        for b in BANNED:
            if b in a:
                errs.append("#%d [%s] 含禁词「%s」：%s" % (i, tag, b, a[:40]))
        # 4. 空回答
        if not a.strip():
            errs.append("#%d [%s] 空回答" % (i, tag))

    print("生成 %d 条" % len(RECORDS))
    print("\n按类：")
    for k in sorted(by_tag):
        print("  %s 类 %3d 条" % (k, by_tag[k]))
    print("\n按目标题（每条对准一道评测题）：")
    for k in sorted(by_target):
        print("  %-6s %3d 条" % (k, by_target[k]))

    print("\n自检：")
    if errs:
        print("  ❌ %d 处问题：" % len(errs))
        for e in errs[:15]:
            print("    " + e)
    else:
        print("  ✅ 全部通过（≤80 字 / 无问号结尾 / 29 个客服腔词零命中 / 无空回答）")
    return len(errs)


