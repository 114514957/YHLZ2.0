def call(key: str, user: str) -> str:
    body = json.dumps({
        "model": "deepseek-flash",
        "messages": [{"role": "system", "content": SYS},
                     {"role": "user", "content": user}],
        "temperature": 0.95, "max_tokens": 2600, "stream": False,
        "thinking": {"type": "disabled"},
    }).encode()
    req = urllib.request.Request("https://api.deepseek.com/chat/completions", data=body,
                                 headers={"Authorization": "Bearer " + key,
                                          "Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=240) as r:
        return json.loads(r.read().decode())["choices"][0]["message"].get("content", "")


def convert_compact(blk: str) -> str:
    lines = blk.split("\n")
    out, qi, ai = [], 0, 0
    for ln in lines:
        s = ln.strip()
        m = re.match(r"^(老爹|元亨)\s*[：:]\s*(.+)$", s)
        if m and not s.startswith("#"):
            if m.group(1) == "元亨":
                ai += 1
                out.append("### 元亨答%d" % ai)
            else:
                qi += 1
                out.append("### 老爹问%d" % qi)
            out.append(m.group(2).strip())
        else:
            out.append(ln)
    return "\n".join(out)


def validate(blk: str) -> str:
    if not blk.startswith("## "):
        return "块头不对"
    if not re.search(r"^-\s*category:", blk, re.M):
        return "缺 category"
    if not re.search(r"^###\s*元亨答\d+\s*$", blk, re.M):
        return "没有元亨答"
    if re.search(r"\*[^*\n]{2,}\*|（[^）\n]{1,12}）", blk):
        return "有动作旁白/括号"
    ans = re.findall(r"^###\s*元亨答\d+\s*\n(.+?)(?=\n###|\Z)", blk, re.M | re.S)
    if not ans:
        return "答为空"
    for x in ans:
        x = x.strip()
        if len(x) > 120:
            return "回答过长 %d" % len(x)
        for w in ("我这边", "我接", "我认", "稳了", "很稳", "别指望", "理论上来说"):
            if w in x:
                return "禁词:" + w
    import v9_story_gate as G
    r = G.check_block("x", blk, "general")
    if r["status"] == "FAIL":
        return "；".join(r["fails"])[:54]
    return ""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--cls", default="")
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--per-scene", type=int, default=7)
    ap.add_argument("--start", type=int, default=0, help="场景起点（分批跑）")
    ap.add_argument("--scenes", type=int, default=0, help="本次跑几个场景（0=全部）")
    a = ap.parse_args()

    classes = list(SCENES) if a.all else ([a.cls] if a.cls else ["判断"])
    tasks = []
    for cls in classes:
        for i, sc in enumerate(SCENES[cls]):
            tasks.append((cls, i, sc))
    if a.start or a.scenes:
        tasks = tasks[a.start:a.start + (a.scenes or len(tasks))]
    print("类别 %s ｜场景 %d 个 ｜每场景 %d 条 → 目标约 %d 条"
          % (classes, len(tasks), a.per_scene, len(tasks) * a.per_scene))

    key = load_key()
    kept, failed = [], []
    for n, (cls, idx, sc) in enumerate(tasks, 1):
        user = ("类别：%s\n具体场景：%s\n\n"
                "请写 %d 个**互不相同**的对话块，都围绕这个场景，但切入点、态度、"
                "元亨的立场要各不相同（有的赞同、有的反对、有的半同意、有的扯开）。\n"
                "块编号用 %s-<序号>。提醒：她要有自己的坐标系，不是顶回去，也不是顺从。"
                % (cls, sc, a.per_scene, cls[:1]))
        try:
            resp = call(key, user)
        except Exception as exc:  # noqa: BLE001
            print("  [%d/%d] %s/%s API失败: %s" % (n, len(tasks), cls, sc[:12], str(exc)[:50]))
            continue
        resp = re.sub(r"(?m)^```[a-zA-Z]*\s*$", "", resp)
        parts = re.split(r"(?m)^##\s+", resp)
        got = 0
        for p in parts[1:]:
            blk = "## " + p.strip() + "\n"
            blk = re.sub(r"(?m)^\s*=+\s*$", "", blk).strip() + "\n"
            if not re.search(r"^###\s*\S+[问答]\d+\s*$", blk, re.M):
                blk = convert_compact(blk)
            why = validate(blk)
            if why:
                failed.append((cls, sc[:10], why))
                continue
            kept.append(blk)
            got += 1
        print("  [%2d/%d] %-6s %-16s → %d 条" % (n, len(tasks), cls, sc[:16], got))

    print("\n合计通过 %d 条｜失败 %d 块" % (len(kept), len(failed)))
    from collections import Counter  # noqa: E402
    print("失败原因：%s" % dict(Counter(f[2] for f in failed).most_common(6)))
    if kept:
        os.makedirs(OUT, exist_ok=True)
        p = os.path.join(OUT, "个性生成_%s_%d-%d.md"
                         % (time.strftime("%m%d_%H%M%S"), a.start,
                            a.start + len(tasks)))
        io.open(p, "w", encoding="utf-8").write("\n\n".join(kept) + "\n")
        print("已写 -> %s" % os.path.relpath(p, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
