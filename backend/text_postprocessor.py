    def _load_word_corrections(self) -> dict:
        return defaultdict(list)
    
    def _load_phrase_corrections(self) -> dict:
        return {}
    
    def add_hotwords(self, hotwords: list, weights: dict = None):
        self._hotwords.extend(hotwords)
        if weights:
            self._hotword_weights.update(weights)
        logger.info(f"热词已更新: {hotwords}")
    
    def set_confidence_threshold(self, threshold: float):
        self._confidence_threshold = threshold
        logger.info(f"置信度阈值已设置为: {threshold}")
    
    def correct_common_errors(self, text: str) -> str:
        for error, correction in self._common_errors.items():
            text = text.replace(error, correction)
        return text
    
    def correct_by_dict(self, text: str, custom_dict: dict = None) -> str:
        corrections = custom_dict if custom_dict else self._word_corrections
        
        for word, corrections_list in corrections.items():
            if word in text:
                for correction in corrections_list:
                    if correction in text:
                        continue
                    text = text.replace(word, correction)
                    break
        
        return text
    
    def apply_hotword_replacement(self, text: str) -> str:
        if not self._hotwords:
            return text
        
        for hotword in self._hotwords:
            if hotword in text:
                continue
            
            hotword_lower = hotword.lower()
            text_lower = text.lower()
            
            if hotword_lower in text_lower:
                matches = re.finditer(re.escape(hotword_lower), text_lower)
                for match in matches:
                    start, end = match.span()
                    text = text[:start] + hotword + text[end:]
        
        return text
    
    def traditional_to_simplified(self, text: str) -> str:
        if self._opencc_converter:
            try:
                return self._opencc_converter.convert(text)
            except Exception as e:
                logger.warning(f"OpenCC转换失败: {e}")
        
        result = []
        for char in text:
            if char in self._traditional_to_simplified:
                result.append(self._traditional_to_simplified[char])
            else:
                result.append(char)
        return ''.join(result)
    
    def simplified_to_traditional(self, text: str) -> str:
        if self._opencc_converter_st:
            try:
                return self._opencc_converter_st.convert(text)
            except Exception as e:
                logger.warning(f"OpenCC转换失败: {e}")
        
        result = []
        for char in text:
            if char in self._simplified_to_traditional:
                result.append(self._simplified_to_traditional[char])
            else:
                result.append(char)
        return ''.join(result)
    
    def normalize_punctuation(self, text: str) -> str:
        for cn_punct, en_punct in self._punctuation_map.items():
            text = text.replace(cn_punct, en_punct)
        
        text = re.sub(r'[。，！？；：]', lambda m: {'。': '.', '，': ',', '！': '!', '？': '?', '；': ';', '：': ':'}[m.group()], text)
        
        return text
    
    def remove_repeated_characters(self, text: str, max_repeats: int = 2) -> str:
        pattern = rf'(.)\1{{{max_repeats},}}'
        text = re.sub(pattern, r'\1' * max_repeats, text)
        
        return text
    
    def remove_special_characters(self, text: str, keep_punctuation: bool = True) -> str:
        if keep_punctuation:
            text = re.sub(r'[^\w\u4e00-\u9fff。，！？；：、""''（）【】《》]', '', text)
        else:
            text = re.sub(r'[^\w\u4e00-\u9fff]', '', text)
        
        return text
    
    def _correct_pinyin_errors(self, text: str) -> str:
        try:
            import pypinyin
            pinyin_result = pypinyin.lazy_pinyin(text)
            pinyin_str = ' '.join(pinyin_result)
            
            for pinyin, correction in self._pinyin_corrections.items():
                if pinyin in pinyin_str:
                    logger.debug(f"拼音纠错: {pinyin} -> {correction}")
                    return correction
            
            return text
        except ImportError:
            return text
    
    def clean_text(self, text: str, convert_traditional: bool = True) -> str:
        text = text.strip()
        
        if convert_traditional:
            text = self.traditional_to_simplified(text)
            logger.debug("已进行繁简体转换")
        
        text = self.remove_repeated_characters(text)
        
        text = self.remove_special_characters(text)
        
        text = self.correct_common_errors(text)
        
        text = self._correct_pinyin_errors(text)
        
        text = self.apply_hotword_replacement(text)
        
        text = self.normalize_punctuation(text)
        
        return text.strip()
    
    def filter_by_confidence(self, text: str, confidence: float) -> tuple:
        if confidence < self._min_confidence_segment:
            logger.warning(f"置信度过低({confidence:.2f})，标记为不可靠")
            return text, False
        
        if confidence < self._confidence_threshold:
            logger.warning(f"置信度较低({confidence:.2f})，建议重识别")
            return text, False
        
        return text, True
    
    def score_text_similarity(self, text1: str, text2: str) -> float:
        text1_clean = re.sub(r'\s+', '', text1)
        text2_clean = re.sub(r'\s+', '', text2)
        
        if not text1_clean or not text2_clean:
            return 0.0
        
        intersection = set(text1_clean) & set(text2_clean)
        union = set(text1_clean) | set(text2_clean)
        
        if not union:
            return 0.0
        
        return len(intersection) / len(union)
    
    def merge_segments(self, segments: list) -> str:
        if not segments:
            return ""
        
        merged = segments[0].get("text", "")
        
        for seg in segments[1:]:
            seg_text = seg.get("text", "")
            if seg_text:
                if merged and not merged.endswith(('。', '！', '？', ',', '.', '!', '?')):
                    merged += "，" + seg_text
                else:
                    merged += seg_text
        
        return merged
    
    def extract_high_confidence_segments(self, segments: list, threshold: float = -0.5) -> list:
        return [seg for seg in segments if seg.get("avg_logprob", 0) >= threshold]
    
    def get_segment_confidence(self, segment) -> float:
        if hasattr(segment, 'avg_logprob'):
            return segment.avg_logprob
        return segment.get("avg_logprob", -1.0)
    
    def postprocess(self, text: str, segments: list = None, confidence: float = None) -> dict:
        result = {
            "original_text": text,
            "cleaned_text": "",
            "is_reliable": True,
            "confidence": confidence,
            "suggestions": []
        }
        
        cleaned = self.clean_text(text)
        result["cleaned_text"] = cleaned
        
        if confidence is not None:
            _, is_reliable = self.filter_by_confidence(text, confidence)
            result["is_reliable"] = is_reliable
            
            if not is_reliable:
                result["suggestions"].append("置信度过低，建议重识别")
        
        if segments:
            high_conf_segments = self.extract_high_confidence_segments(segments)
            if len(high_conf_segments) < len(segments):
                result["suggestions"].append(f"部分片段置信度低，已过滤{len(segments) - len(high_conf_segments)}个片段")
        
        if len(cleaned) != len(text):
            result["suggestions"].append("文本已进行清洗和纠错")
        
        return result
    
    def batch_postprocess(self, texts: list, segments_list: list = None, 
                          confidences: list = None) -> list:
        results = []
        
        for i, text in enumerate(texts):
            segments = segments_list[i] if segments_list else None
            confidence = confidences[i] if confidences else None
            results.append(self.postprocess(text, segments, confidence))
        
        return results


